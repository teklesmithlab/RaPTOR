def find_imaginary_nodes_cation(directory, xyz_stem=RADICAL_CATION_STEM):
    """Same check as functions.find_imaginary_nodes, for the fixed radical-cation filename."""
    filename = f"fairchem_{xyz_stem}.xyz.out"
    filepath = os.path.join(directory, filename)

    if not os.path.isfile(filepath):
        raise FileNotFoundError(f"File not found: {filepath}")

    with open(filepath, "r") as f:
        for line in f:
            if "Total imaginary modes:" in line:
                modes = int(re.search(r"(\d+)", line).group(1))
                return modes > 0

    return False


def read_philicity_cation(folder_directory):
    """
    Radical-cation analog of functions.read_philicity. The charge ladder is
    shifted up by one relative to the neutral-radical case:

        neutral radical pipeline:  anion(-1) / radical(0)  / cation(+1)
        radical cation pipeline:   neutral(0) / rad.cation(+1) / dication(+2)

    so I/A/philicity are defined the same way, just against the radical
    cation's own SCF energy instead of the neutral radical's.
    """
    neutral_scf = read_scf_energy(f'{folder_directory}/DFT_elec_neutral.out')
    radicalcation_scf = read_scf_energy(f'{folder_directory}/DFT_elec_radicalcation.out')
    dication_scf = read_scf_energy(f'{folder_directory}/DFT_elec_dication.out')

    I = (dication_scf - radicalcation_scf) * 27.2114
    A = (radicalcation_scf - neutral_scf) * 27.2114

    philicity = ((I + A) ** 2) / (I - A) * (1 / 8)

    return I, A, philicity
