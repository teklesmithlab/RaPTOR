RADICAL_CATION_STEM = "radicalcation"  # fixed identifier: one calc per molecule, no {h}H index needed

# SMARTS for N atoms that should NOT be treated as the oxidized amine site
_AMIDE_N = Chem.MolFromSmarts("[N][C]=[O,S]")


def _radical_cation_center_from_mulliken(out_file: Path, mol) -> int | None:
    """
    Parse DFT_elec_radicalcation.out and return the heavy-atom index (in mol
    WITHOUT explicit H) of the N with the highest Mulliken spin population.

    ORCA writes Mulliken populations with 0-based atom indices in the same
    order as the input xyz, which was generated by RDKit AddHs (heavy atoms
    first, H appended). So ORCA atom index k maps directly to
    mol.GetAtomWithIdx(k) for k < mol.GetNumAtoms().

    Returns None if the file is missing, unparseable, the max-spin atom is H,
    or no N has spin > 0.1 (spin too diffuse to assign unambiguously).
    """
    try:
        text = out_file.read_text()
    except Exception:
        return None

    blocks = list(re.finditer(
        r"MULLIKEN ATOMIC CHARGES AND SPIN POPULATIONS\s*\n-+\n(.*?)\nSum of atomic charges",
        text, re.S,
    ))
    if not blocks:
        return None

    atom_spins: dict[int, tuple[str, float]] = {}
    for line in blocks[-1].group(1).splitlines():
        m = re.match(r"\s*(\d+)\s+(\S+)\s*:\s*[-\d.]+\s+([-\d.]+)", line)
        if m:
            atom_spins[int(m.group(1))] = (m.group(2), float(m.group(3)))

    if not atom_spins:
        return None

    n_heavy = mol.GetNumAtoms()  # mol without explicit H; heavy atoms occupy indices 0..n_heavy-1
    n_candidates = [(idx, spin) for idx, (elem, spin) in atom_spins.items()
                    if elem == "N" and spin > 0.1 and idx < n_heavy]
    if not n_candidates:
        return None

    return max(n_candidates, key=lambda x: x[1])[0]


def neutral_to_radical_cation_smiles(neutral_smiles: str, mol_dir=None) -> str | None:
    """
    Convert a neutral amine SMILES to its radical-cation SMILES.

    Amine radical cations are formed by removing one electron from the amine N
    lone pair (no H abstraction, no bond breaking). The result has formal charge
    +1 and 1 radical electron on N, with all hydrogens intact.

    We cannot derive this from xyz_to_smiles/obabel because standard xyz files
    carry no charge/spin info — obabel returns neutral SMILES, giving
    GetNumRadicalElectrons()=0 everywhere and silently dropping the row.

    Implementation: AddHs to make implicit H explicit → set charge+1, radical=1,
    NoImplicit on N → RemoveHs → canonical SMILES. The AddHs step is essential:
    without it, NoImplicit removes the implicit H from the radical cation.

    When multiple aliphatic, non-amide Ns are present and mol_dir is provided,
    Mulliken spin populations from DFT_elec_radicalcation.out are used to
    identify the actual radical site. Falls back to the most-substituted-N
    heuristic (most heavy-atom neighbors) when the DFT file is unavailable or
    unparseable.

    Returns None (row is skipped) if:
      - SMILES is invalid
      - no aliphatic, non-amide, uncharged N is found
    """
    mol = Chem.MolFromSmiles(neutral_smiles)
    if mol is None:
        return None

    amide_n_idxs: set[int] = (
        {m[0] for m in mol.GetSubstructMatches(_AMIDE_N)} if _AMIDE_N else set()
    )

    amine_idxs = [
        a.GetIdx()
        for a in mol.GetAtoms()
        if a.GetSymbol() == "N"
        and not a.GetIsAromatic()
        and a.GetFormalCharge() == 0
        and a.GetIdx() not in amide_n_idxs
    ]

    if len(amine_idxs) == 0:
        return None

    if len(amine_idxs) == 1:
        chosen_idx = amine_idxs[0]
    else:
        # Try Mulliken spin from the actual DFT single point — this tells us
        # which N the radical actually sits on in the computed geometry.
        chosen_idx = None
        if mol_dir is not None:
            out_file = Path(mol_dir) / "DFT_elec_radicalcation.out"
            mulliken_idx = _radical_cation_center_from_mulliken(out_file, mol)
            if mulliken_idx is not None and mulliken_idx in amine_idxs:
                chosen_idx = mulliken_idx

        if chosen_idx is None:
            # Fall back: most substituted N (most heavy-atom neighbors)
            chosen_idx = max(amine_idxs, key=lambda i: sum(
                1 for nb in mol.GetAtomWithIdx(i).GetNeighbors() if nb.GetAtomicNum() != 1
            ))

    # AddHs first so implicit H atoms become explicit — they survive RemoveHs.
    # chosen_idx is the heavy-atom index in mol (no explicit H), which equals
    # the atom index in the AddHs mol because AddHs appends H after all heavy atoms.
    rw = Chem.RWMol(Chem.AddHs(mol))
    n_atom = rw.GetAtomWithIdx(chosen_idx)
    n_atom.SetFormalCharge(1)
    n_atom.SetNumRadicalElectrons(1)
    n_atom.SetNoImplicit(True)

    try:
        Chem.SanitizeMol(rw)
        return Chem.MolToSmiles(Chem.RemoveHs(rw))
    except Exception:
        return None


