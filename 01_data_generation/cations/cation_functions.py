"""
Helper functions for the amine radical-cation pipeline.

Unlike the neutral-radical pipeline (functions.py), radical cations are not
generated by abstracting a hydrogen atom -- they're generated by ionizing the
intact neutral molecule (removing one electron from the lone pair, no bond
broken). That means there is exactly ONE radical-cation species per parent
molecule (modulo conformers), so there is no per-hydrogen enumeration/split
step, and the reference charge ladder shifts from {-1, 0, +1} (anion/neutral
radical/cation) to {0, +1, +2} (neutral/radical cation/dication).

This module only adds the pieces that differ from functions.py (the FairChem
call at charge +1, the read-back of the shifted philicity ladder, and the
imaginary-mode check for the new file naming). Everything else reusable --
xtb pre-opt, GOAT conformer search, ORCA .inp submission, locked CSV
appends -- is imported directly from functions.py rather than duplicated.
"""

